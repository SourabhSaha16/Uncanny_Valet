namespace UncannyValet.UI.Kit
{
    /// <summary>
    /// The 5x7 bitmap font as plain data: seven rows of five bits per glyph (bit 4 is the left column).
    /// Lower case is drawn as upper case; anything unknown is drawn as '?'.
    /// </summary>
    public static class PixelGlyphs
    {
        public const int Width = 5;
        public const int Height = 7;
        public const char Fallback = '?';

        /// <summary>The characters with a glyph, in table order.</summary>
        public const string Chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .,:!?-+/$%'#()*";

        /// <summary>Row data, <see cref="Height"/> bytes per entry of <see cref="Chars"/>.</summary>
        public static readonly byte[] Rows =
        {
            0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11, // A
            0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E, // B
